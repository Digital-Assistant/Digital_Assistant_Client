#!/usr/bin/env bash
# Writes environments/<build>.env from environment variables, for CI.
# Each schema key in environments/env.example is read from the UPPER_SNAKE variable
# of the same name (baseProdURL <- BASE_PROD_URL, keycloakClientId <- KEYCLOAK_CLIENT_ID).
# In GitHub Actions those come from Actions variables (vars.*; organization-level,
# shared with the SDK repo), never from secrets:
# every value ends up in the public extension bundle.
# Unset variables are written empty (allowed: the build then has no URL for that key).
# Prints key names only, never values.
#
# Usage: scripts/ci/generate-env.sh [--build NAME] [--force] [--print-names]
#   --build NAME    target environments/NAME.env (default: production)
#   --force         overwrite an existing file (always allowed when CI=true)
#   --print-names   print "schemaKey VARIABLE_NAME" pairs and exit
set -euo pipefail
cd "$(dirname "$0")/../.."

build=production
force=false
print_names=false
while (( $# )); do
  case "$1" in
    --build) build="${2:?--build needs a name}"; shift 2 ;;
    --force|-f) force=true; shift ;;
    --print-names) print_names=true; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
[[ "$build" =~ ^[A-Za-z0-9_-]+$ ]] || { echo "invalid build name: $build" >&2; exit 2; }

to_upper_snake() {
  sed -E 's/([a-z0-9])([A-Z])/\1_\2/g; s/([A-Z])([A-Z][a-z])/\1_\2/g' <<<"$1" | tr '[:lower:]' '[:upper:]'
}

mapfile -t KEYS < <(node scripts/build-env.js "$build" --schema)
(( ${#KEYS[@]} > 0 )) || { echo "no keys in environments/env.example" >&2; exit 1; }

if [[ "$print_names" == true ]]; then
  for k in "${KEYS[@]}"; do echo "$k $(to_upper_snake "$k")"; done
  exit 0
fi

target="environments/${build}.env"
if [[ -e "$target" && "$force" != true && "${CI:-}" != true ]]; then
  echo "$target exists; refusing to overwrite a local file (pass --force)." >&2
  exit 1
fi

tmp="$(mktemp "environments/.${build}.env.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by scripts/ci/generate-env.sh. Do not commit. Public values only."
  echo "# Build: ${build}"
} >"$tmp"

set_names=()
unset_names=()
for k in "${KEYS[@]}"; do
  var="$(to_upper_snake "$k")"
  val="${!var:-}"
  if [[ "$val" == *$'\n'* || "$val" == *$'\r'* ]]; then
    echo "$var contains a line break; refusing." >&2
    exit 1
  fi
  if [[ -n "$val" ]]; then set_names+=("$k"); else unset_names+=("$k"); fi
  esc="${val//\\/\\\\}"
  esc="${esc//\"/\\\"}"
  printf '%s="%s"\n' "$k" "$esc" >>"$tmp"
done

mv "$tmp" "$target"
trap - EXIT
echo "Wrote $target: ${#set_names[@]}/${#KEYS[@]} keys set."
(( ${#set_names[@]} )) && echo "  set:   ${set_names[*]}"
(( ${#unset_names[@]} )) && echo "  empty: ${unset_names[*]}"
exit 0
